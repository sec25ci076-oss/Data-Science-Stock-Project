import pandas as pd
import matplotlib.pyplot as plt

# 1. Definitive fallback plotting function using stable visual rendering
def make_graph(stock_data, revenue_data, stock):
    # Sort data entries chronologically
    stock_sorted = stock_data.sort_values(by="Date")
    rev_sorted = revenue_data.sort_values(by="Date")

    # Initialize the visual grid panels
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8), sharex=False)

    # Provide the exact mandatory title for the graph canvas
    fig.suptitle(f"{stock} Historical Stock and Revenue Dashboard", fontsize=16, fontweight='bold')

    # Chart Panel 1: Historical Share Price
    ax1.plot(pd.to_datetime(stock_sorted['Date']), stock_sorted['Close'].astype(float), color='#007acc', linewidth=2.5)
    ax1.set_title("Historical Share Price")
    ax1.set_ylabel("Price ($US)")
    ax1.grid(True, linestyle='--', alpha=0.5)

    # Chart Panel 2: Historical Revenue
    ax2.plot(pd.to_datetime(rev_sorted['Date']), rev_sorted['Revenue'].astype(float), color='#ff7f0e', linewidth=2.5)
    ax2.set_title("Historical Revenue")
    ax2.set_xlabel("Date")
    ax2.set_ylabel("Revenue ($US Millions)")
    ax2.grid(True, linestyle='--', alpha=0.5)

    # Standard output packaging to prevent blank space errors
    plt.tight_layout()
    plt.show()