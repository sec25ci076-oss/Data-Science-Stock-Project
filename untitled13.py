# Commented out IPython magic to ensure Python compatibility.
# Force Jupyter to wake up its inline graph printing engine
# %matplotlib inline

import pandas as pd
import matplotlib.pyplot as plt

# 1. Plotting Function Definition
def make_graph(stock_data, revenue_data, stock):
    # Chronological data sorting
    stock_sorted = stock_data.sort_values(by="Date")
    rev_sorted = revenue_data.sort_values(by="Date")

    # Instantiate the visual frame grid
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8), sharex=False)

    # Explicit title string allocation
    fig.suptitle(f"{stock} Historical Stock and Revenue Dashboard", fontsize=16, fontweight='bold')

    # Panel 1: Price Track
    ax1.plot(pd.to_datetime(stock_sorted['Date']), stock_sorted['Close'].astype(float), color='#007acc', linewidth=2.5)
    ax1.set_title("Historical Share Price")
    ax1.set_ylabel("Price ($US)")
    ax1.grid(True, linestyle='--', alpha=0.5)

    # Panel 2: Revenue Track
    ax2.plot(pd.to_datetime(rev_sorted['Date']), rev_sorted['Revenue'].astype(float), color='#ff7f0e', linewidth=2.5)
    ax2.set_title("Historical Revenue")
    ax2.set_xlabel("Date")
    ax2.set_ylabel("Revenue ($US Millions)")
    ax2.grid(True, linestyle='--', alpha=0.5)

    # Clean padding distribution layouts
    plt.tight_layout()

    # Final force-print command to bypass display blocks
    plt.show()

# Let's verify the plotting function with some dummy data.
# Often, issues with graphs not displaying occur if the 'Close' or 'Revenue' columns
# contain non-numeric characters (like '$' or ',') or if the DataFrame is empty.

# Create clean sample data
sample_stock = pd.DataFrame({
    'Date': ['2023-01-01', '2023-02-01', '2023-03-01'],
    'Close': [150.0, 160.0, 155.0]
})

sample_revenue = pd.DataFrame({
    'Date': ['2023-01-01', '2023-02-01', '2023-03-01'],
    'Revenue': [100.0, 120.0, 110.0]
})

# Call the function to test rendering
make_graph(sample_stock, sample_revenue, "Test Stock")